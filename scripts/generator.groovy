def packageName = properties['grace.codegen.defaultPackage'] ?: ''
def profileName = properties['grace.profile'] ?: ''
def features = properties['grace.app.features'] ?: ''

def prevVersions = options['version-prev']?.split(',')
def nextVersions = options['version-next']?.split(',')

def versionUrls = []
def versionDiffs = []
prevVersions?.each {
    versionUrls << "* https://github.com/rainboyan/grace-versions/compare/v" + it + '...v' + graceVersion
    versionDiffs << "git diff v" + it + "..v" + graceVersion
}
nextVersions?.each {
    versionUrls << "* https://github.com/rainboyan/grace-versions/compare/v" + graceVersion + '...v' + it
    versionDiffs << "git diff v" + graceVersion + "..v" + it
}

def versionUrlStrs = versionUrls.join('\n')
def versionDiffStrs = versionDiffs.join('\n')

